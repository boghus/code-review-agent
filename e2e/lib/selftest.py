def test_provider_failure_beats_structural_failures():
    """A provider outage must not be classified as an action defect.

    When the provider is unreachable the action renders no severity summary,
    so the structural checks fail too. Those structural checks are tagged
    ``provider`` when the body reports an outage, and provider-first priority
    keeps the verdict on the infrastructure instead of the product.
    """
    body = (MARKER + "\n## ⚠️ Code Review Agent by boghus unavailable\n\n"
            "Quota exhausted for **gemini**.\n\n"
            "The automated review is non-blocking.\n")
    checks = assert_valid_review(body, min_counts=(1, 0, 0, 0), expect_severity="CRITICAL")

    structural = [c for c in checks if not c.ok and c.failure_class == "action"]
    ok = classify_failure(checks) == "provider" and not structural
    print("%s provider outage reclassified, %d structural checks mis-tagged"
          % ("PASS" if ok else "FAIL", len(structural)))
    return ok


def test_fixture_content_is_plain_text():
    """The fixture must be applied verbatim, not base64 encoded.

    The git trees endpoint takes the content as plain text. Encoding it, as
    the contents endpoint requires, silently produced a fixture file that held
    base64 and no readable source.
    """
    from runner import _fixture_content
    import scenarios as scenario_registry

    scenario = scenario_registry.SCENARIOS_BY_NAME["clean"]
    content, path, _sha = _fixture_content(scenario)
    ok = content is not None and "package " in content and "class " in content
    ok = ok and not content.strip().startswith("cGFja2FnZ")
    print("%s fixture content is plain source (%s)"
          % ("PASS" if ok else "FAIL", path))
    return ok


def test_every_scenario_pins_its_fixture():
    """Every scenario must pin a fixture commit.

    A branch can move, so a fixture resolved from a branch would let an
    accidental push change the scenario of a release. A commit SHA cannot
    move, so it is what pins the fixture, and a scenario without one cannot
    run deterministically.
    """
    import scenarios as scenario_registry

    unpinned = [name for name in scenario_registry.SCENARIO_NAMES
                if not scenario_registry.FIXTURE_SHAS.get(name)]
    ok = not unpinned
    print("%s every scenario pins a fixture commit (%s)"
          % ("PASS" if ok else "FAIL", unpinned or "all pinned"))

    bad = [name for name, sha in scenario_registry.FIXTURE_SHAS.items()
           if sha and len(sha) != 40]
    ok = ok and not bad
    print("%s every pinned SHA is a full commit SHA (%s)"
          % ("PASS" if ok else "FAIL", bad or "all full"))
    return ok


def test_skipped_is_not_a_provider_outage():
    """A skip is a setup problem, not an infrastructure outage.

    Treating a skip as a provider failure would retry it as infrastructure
    and report it as an outage, when it is a defect in the configuration or
    the rules that will not clear on its own.
    """
    body = (MARKER + "\n## ⚠️ Code Review Agent by boghus skipped\n\n"
            "The rules file could not be read.\n\n"
            "This is non-blocking; fix the configuration or rules and re-run.\n")
    ok = not is_provider_failure(body) and is_skipped(body)
    print("%s skipped is not classified as a provider outage" % ("PASS" if ok else "FAIL"))
    return ok


def test_missing_location_fails_when_files_are_expected():
    """A review with no file:line must fail when the scenario pins a file.

    The location check only rejects unexpected paths, so an empty list of
    locations passes it. A scenario that pins a file expects the finding to
    point at it.
    """
    body = render([finding("CRITICAL", "Sin ubicacion", None, None,
                           description="Sin ruta ni linea")], summary="Un hallazgo.")
    checks = assert_valid_review(body, expected_files={"e2e/fixtures/critical/ConfigFixture.groovy"},
                                  min_counts=(1, 0, 0, 0), expect_severity="CRITICAL")
    location_check = [c for c in checks if c.name == "finding locations present"]
    ok = bool(location_check) and not location_check[0].ok
    print("%s a missing location fails the check (%s)"
          % ("PASS" if ok else "FAIL", location_check[0].detail if location_check else "no check"))
    return ok


def test_action_checks_survive_a_provider_outage():
    """A structural defect must not disappear behind a provider outage.

    The provider reclassification used to replace the whole check list, so a
    duplicated marker reported alongside an outage was dropped and the retry
    could report a pass.
    """
    body = (MARKER + "\n## ⚠️ Code Review Agent by boghus unavailable\n\n"
            "Quota exhausted.\n\nThe automated review is non-blocking.\n" + MARKER)
    checks = assert_identity(body)
    duplicated = [c for c in checks if c.name == "marker appears exactly once"]
    ok = bool(duplicated) and not duplicated[0].ok
    print("%s the duplicated marker is still reported during an outage"
          % ("PASS" if ok else "FAIL"))
    return ok


def main():
    case("clean en", test_clean_english)
    case("clean es", test_clean_spanish)
    case("clean rejects findings", test_clean_rejects_findings)
    case("critical", test_critical)
    case("high", test_high)
    case("medium es", test_medium_spanish)
    case("multiple findings", test_multiple_findings_count_agreement)
    case("singular wording", test_singular_finding_wording)
    case("provider failure", test_provider_failure)
    case("provider != clean", test_provider_failure_not_mistaken_for_clean)
    case("duplicate marker", test_marker_duplicated_is_action_failure)
    case("secret detection", test_secret_detection)
    case("fixture secret", test_fixture_secret_does_not_break_own_assertion)
    case("failure classification", test_classify_failure)
    case("heading constant", test_ai_heading_constant)
    case("extra findings tolerated", test_extra_findings_are_tolerated)
    case("prose URL not a location", test_location_regex_ignores_prose_urls)
    case("missing severity fails", test_missing_expected_severity_fails)
    case("provider reclassified", test_provider_failure_beats_structural_failures)
    case("fixture is plain text", test_fixture_content_is_plain_text)
    case("fixtures are pinned", test_every_scenario_pins_its_fixture)
    case("skipped is not an outage", test_skipped_is_not_a_provider_outage)
    case("missing location fails", test_missing_location_fails_when_files_are_expected)
    case("action checks survive outage", test_action_checks_survive_a_provider_outage)

    print()
    passed = sum(1 for _, ok in RESULTS if ok)
    for name, ok in RESULTS:
        print("%s %s" % ("PASS" if ok else "FAIL", name))
    print("\n%d/%d PASS" % (passed, len(RESULTS)))
    return 0 if passed == len(RESULTS) else 1


if __name__ == "__main__":
    sys.exit(main())