def test_marker_duplicated_is_action_failure():
    body = render([]) + "\n\n" + MARKER + "\n"
    checks = assert_identity(body)
    dup = [c for c in checks if c.name == "marker appears exactly once"][0]
    ok = not dup.ok and dup.failure_class == "action"
    print("%s duplicate marker is detected as an action failure" % ("PASS" if ok else "FAIL"))
    return ok


def test_secret_detection():
    leaked = find_secrets(MARKER + "\nkey AIzaSyDUMMYDUMMYDUMMY12345 and ghp_abcdefghijklmnop")
    ok = len(leaked) == 2
    print("%s secret detection (%s)" % ("PASS" if ok else "FAIL", leaked))
    checks = assert_identity(MARKER + "\nAIzaSyDUMMYDUMMYDUMMY12345")
    secret_check = [c for c in checks if c.name == "no secrets in comment"][0]
    ok = ok and not secret_check.ok and secret_check.failure_class == "action"
    return ok


def test_fixture_secret_does_not_break_own_assertion():
    """The CRITICAL fixture contains a fake key; the assertion must catch it."""
    body = render([finding("CRITICAL", "Hardcoded key", "x.groovy", 1,
                           description="Found AIzaSyFIXTUREVALUE1234567890 inline")])
    checks = assert_valid_review(body, expected_counts=(1, 0, 0, 0), expect_severity="CRITICAL")
    secret_check = [c for c in checks if c.name == "no secrets in comment"][0]
    ok = not secret_check.ok
    print("%s fixture secret is detected even when the finding is correct" % ("PASS" if ok else "FAIL"))
    return ok


