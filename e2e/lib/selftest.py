def test_provider_failure_not_mistaken_for_clean():
    body = (MARKER + "\n## ⚠️ Code Review Agent by boghus unavailable\n\n"
            "boom\n\nThe automated review is non-blocking.\n")
    ok = is_non_ai_report(body) and parse_severity_counts(body) is None
    ok = ok and not assert_clean_review(body)[0].ok is False
    ok = ok and all(not c.ok for c in assert_clean_review(body)
                    if c.name in ("severity summary matches fixture",
                                  "renders no-findings notice"))
    print("%s provider failure is not accepted as a clean review" % ("PASS" if ok else "FAIL"))
    return ok


