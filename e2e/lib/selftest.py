def test_clean_rejects_findings():
    checks = assert_clean_review(render([finding("LOW", "style", "a.groovy", 1)]))
    failing = [c for c in checks if not c.ok]
    ok = len(failing) >= 1 and all(c.failure_class == "llm_variance" for c in failing)
    print("%s clean rejects findings (%d failing checks)"
          % ("PASS" if ok else "FAIL", len(failing)))
    return ok


